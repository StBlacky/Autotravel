    <h3>Зачем нужна корзина</h3>
    <div class="note-block">
Корзина — это удобный способ собрать интересные объекты в один план поездки.<br>
Как в интернет-магазине вы складываете товары в корзину, так здесь вы складываете места: музеи, храмы, смотровые точки, города, участки дорог.<br>
Сначала — сбор. Потом — порядок.<br>
Дальше вы можете разбить поездку на дни, переставить точки, добавить заметки и собрать логистику так, как удобно именно вам.<br>
    </div>

    <h3>Нужно ли регистрироваться</h3>
    <div class="note-block">
Да.<br>
Редактировать корзину может только её владелец.<br>
Просматривать корзину по ссылке могут все.<br>
    </div>

    <h3>Как добавить объект в корзину</h3>
    <div class="note-block">
Обычно — кнопкой «Добавить в корзину» на странице объекта.<br>
Если вы уже в корзине — можно добавлять точки внутри нужного блока поездки.<br>
    </div>

    <h3>Что такое «блок» в корзине</h3>
    <div class="note-block">
Блок — это часть поездки, которую вы задаёте сами. <br>
Первый блок создается автоматически и автоматически нумеруется. Вы можете его переименовать.
Например: «День 1», «День 2», «Дорога», «Пеший маршрут», «Резерв».<br>
Внутри блока — объекты и ваши комментарии в нужной последовательности.<br>
Вы можете создавать столько блоков, сколько нужно для логики Вашей поездки.
<br>
    </div>

    <h3>Можно ли менять порядок точек</h3>
    <div class="note-block">
Да.<br>
Блоки и точки внутри блоков можно перетаскивать мышкой (drag&drop).<br>
Так удобнее всего быстро собрать логистику и порядок посещения.<br>
    </div>

    <h3>Можно ли добавлять свои заметки</h3>
    <div class="note-block">
Да.<br>
В корзину можно вставлять комментарии: планы, время, ориентиры, список задач, бюджет, «что не забыть».<br>
    </div>

    <h3>Сохраняется ли всё автоматически</h3>
    <div class="note-block">
Да.<br>
Текст и изменения сохраняются автоматически.<br>
    </div>

    <h3>Можно ли использовать корзину как готовый маршрут</h3>
    <div class="note-block">
Да.<br>
Корзина может быть вашим финальным планом поездки: точки идут в нужной последовательности, а вся поездка или отдельный блок отображаются на карте.<br>
При необходимости точки можно выгружать (списком объектов через карту) и использовать в навигации.<br>
Важно: Autotravel не прокладывает GPS-маршрут автоматически — корзина помогает планировать и выстраивать логистику, а не заменяет навигатор.<br>
    </div>

    <h3>Можно ли поделиться корзиной</h3>
    <div class="note-block">
Да.<br>
Если у человека есть ссылка, он сможет открыть корзину и посмотреть план.<br>
Редактировать корзину может только владелец.<br>
    </div>

    <h3>Если я удалю объект из корзины — он исчезнет с сайта</h3>
    <div class="note-block">
Нет.<br>
Вы удаляете объект только из своей корзины. На сайте он остаётся.<br>
    </div>
       <h3>Можно ли иметь несколько корзин</h3>
    <div class="note-block">
Да.<br>
У одного пользователя может быть несколько корзин — под разные поездки, годы или идеи «на будущее».<br>
Управление корзинами находится в личном кабинете в разделе «Мои поездки».<br>
Там можно создавать новые корзины, переименовывать их и выбирать актуальную.<br>
Объекты, которые вы добавляете с сайта, по умолчанию попадают в выбранную (актуальную) корзину.<br>
    </div>

