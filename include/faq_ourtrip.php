    <h3>Как присоединиться к совместной поездке</h3>
    <div class="note-block">
Для того чтобы приобщиться к священному братству автопутешественников 
нашего сайта (форума), путешествующему мини-сообществами, нужно совсем немного:<br>
1. Внимательно прочитать информацию о понравившейся поездке.<br>
2. Зарегистрироваться на форуме (это бесплатно но требует работающего почтового ящика)<br>
3. Выразить свое желание участвовать в существующей поездке или 
организовать новую поездку в календаре на сайте.<br>
    </div>

    <h3>Состав группы и статусы участников</h3>
    <div class="note-block">
СОСТАВ ГРУППЫ<br>
Группа набирается по первенству регистрации на экскурсию (в поездку). 
Никаких ограничений по количеству участников, наличию у них детей, джипов 
или вилл на Канарах у нас нет. Такие ограничения могут вводиться только со 
стороны объекта посещения. Если принимающей стороной ограничивается количество 
экскурсантов или введен возрастной ценз, то эти обстоятельства обязательно 
отражаются в информации к поездке.<br>
Каждый зарегистрированный участник поездки имеет один из статусов:<br>
— организатор<br>
— участник<br>
— желающий<br>
    </div>

    <h3>Организатор</h3>
    <div class="note-block">
ОРГАНИЗАТОР<br>
Организатор поездки — вольный форумчанин, взваливший на себя 
организационные хлопоты. Никаких преференций он не имеет: информация добывается 
как может — интернетом, звонками, визитами в учреждения. Поэтому от организатора 
можно получить только общую информацию — цена, время, место и т. п.<br>
    </div>

    <h3>Желающий</h3>
    <div class="note-block">
ЖЕЛАЮЩИЙ — экипаж, выразивший желание участвовать в поездке.  
Состав фиксируется: отдельно взрослые, отдельно дети.  
Если есть свободные места — организатор меняет статус на «Участник».<br>
    </div>

    <h3>Участник</h3>
    <div class="note-block">
УЧАСТНИК — экипаж, которому гарантировано место.  
Если участник не может ехать, важно заблаговременно предупредить организатора, 
чтобы место передали зарегистрированному желающему.<br>
    </div>

    <h3>Как проходит поездка</h3>
    <div class="note-block">
ПОЕЗДКА<br>
Правил по сбору нет — всё обсуждается в теме.  
Обычно едем колонной, замыкает опытный водитель.  
Используем рации, мобильники, ориентиры и флажки.<br>
    </div>

    <h3>Стоимость поездки</h3>
    <div class="note-block">
Цены на экскурсии определяются объектами посещения.  
Иногда требуется предоплата — через организатора или напрямую.<br>
Если цена фиксированная и делится на всех —  
поздний отказ участника может ударить по остальным.<br>
    </div>

    <h3>После поездки</h3>
    <div class="note-block">
После экскурсии желательно поделиться впечатлениями:<br>
— написать отчёт<br>
— оставить отзывы<br>
— загрузить фотографии<br>
Не забудьте поблагодарить организатора на форуме.<br>
    </div>

